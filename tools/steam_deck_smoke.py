"""Run authored OCR fixtures through the installed Deck providers, never capture a game.

Use the plugin's bundled Python 3.13 on the Deck. The fixture directory must contain
dialogue.json from tests/fixtures and the PNGs generated by benchmark_ocr.py.
"""
import argparse
import asyncio
import json
import sys
import time
import unicodedata
from pathlib import Path


async def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fixtures', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--plugin-dir', type=Path, default=Path.home()/'homebrew/plugins/dross-deck-translator')
    parser.add_argument('--settings-dir', type=Path, default=Path.home()/'homebrew/settings/dross-deck-translator')
    args = parser.parse_args()
    sys.path.insert(0, str(args.plugin_dir/'bin/py_modules'))
    sys.path.insert(0, str(args.plugin_dir/'py_modules'))
    from providers.chromescreenai_provider import ChromeScreenAIProvider
    from providers.dross_local import DrossLocalProvider

    settings = json.loads((args.settings_dir/'dross-deck-translator-settings.json').read_text())
    provider = DrossLocalProvider()
    provider.configure({**settings, 'dross_track_encounters': False, 'dross_save_text': False})
    ocr = ChromeScreenAIProvider(plugin_dir=str(args.plugin_dir), model_dir=str(args.settings_dir/'dross-deck-translator/models/screen_ai/resources'))
    samples = json.loads((args.fixtures/'dialogue.json').read_text(encoding='utf-8'))
    report = {'platform': 'Steam Deck LCD; installed Chrome Screen AI and Dross provider; authenticated Workbench connection',
              'scope': 'Synthetic fixtures, no game capture, frontend rendering or physical button press', 'cases': []}
    normalize = lambda text: ''.join(unicodedata.normalize('NFKC', text).split())
    try:
        health = await provider.health()
        assert health['status'] == 'ok' and health['local_only']
        report['translation_model'] = health['translation_model']
        for sample in samples:
            start = time.perf_counter()
            regions = [r.to_dict() for r in await ocr.recognize((args.fixtures/(sample['case']+'.png')).read_bytes(), 'ja')]
            ocr_ms = round((time.perf_counter()-start)*1000)
            if sample['case'] == 'normal':
                assert regions, 'Normal dialogue was not recognized'
            for r in regions:
                box = r['rect']
                assert 0 <= box['left'] < box['right'] <= 1280 and 0 <= box['top'] < box['bottom'] <= 800
            start = time.perf_counter()
            translated = await provider.translate_regions(regions, 'ja', 'en', 'synthetic-deck-test') if regions else []
            translation_ms = round((time.perf_counter()-start)*1000)
            assert [r['rect'] for r in translated] == [r['rect'] for r in regions]
            start = time.perf_counter()
            repeated = await provider.translate_regions(regions, 'ja', 'en', 'synthetic-deck-test') if regions else []
            repeat_ms = round((time.perf_counter()-start)*1000)
            assert repeated == translated
            detected = ''.join(r['text'] for r in regions)
            item = {'case': sample['case'], 'expected': sample['text'], 'detected': detected,
                    'normalized_exact': normalize(detected) == normalize(sample['text']),
                    'ocr_ms': ocr_ms, 'translation_ms': translation_ms, 'repeat_ms': repeat_ms,
                    'regions': translated}
            report['cases'].append(item)
            args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
            print(json.dumps({k: v for k, v in item.items() if k != 'regions'}, ensure_ascii=True), flush=True)
    finally:
        provider.cache.close()
        ocr.stop_worker()


if __name__ == '__main__':
    asyncio.run(main())
